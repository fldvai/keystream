#!/usr/bin/env python3
"""Generate Keystream.Core/Localization/Strings.g.cs from merged.json.

One dictionary per language (12 tables, canonical order id en es pt fr
de ru zh ja ko ar tr), one entry per unique literal (dedupe from the
inventory). Invariant keys carry the same value in every table. The
input carries one member per language code per key. A key missing a
member for some language emits the English value in that dict, and
every gap (key + missing codes, keys sorted, codes in canonical order)
is listed as a warning on stderr; a missing member never raises
KeyError. Re-run after any merge.py change; the file is generated, do
not hand-edit.

Usage: python3 tools/gen_strings.py (from the repo root)
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TREE = HERE.parent
OUT = TREE / "Keystream.Core" / "Localization" / "Strings.g.cs"

# Canonical order (registry order in Localizer.Languages): input member
# code -> generated dict property name.
LANGUAGES = [
    ("id", "Id"), ("en", "En"), ("es", "Es"), ("pt", "Pt"),
    ("fr", "Fr"), ("de", "De"), ("ru", "Ru"), ("zh", "Zh"),
    ("ja", "Ja"), ("ko", "Ko"), ("ar", "Ar"), ("tr", "Tr"),
]


def cs(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    return "".join(out)


def main():
    merged = json.load(open(HERE / "merged.json", encoding="utf-8"))
    keys = sorted(merged)
    # Missing-member fill (see module docstring): resolve every value
    # up front so emission can never hit a missing member.
    values = {code: {} for code, _prop in LANGUAGES}
    gaps = []
    for k in keys:
        entry = merged[k]
        en_value = entry.get("en")
        if not isinstance(en_value, str):
            en_value = entry.get("id", "")
        for code, _prop in LANGUAGES:
            v = entry.get(code)
            if isinstance(v, str):
                values[code][k] = v
            else:
                values[code][k] = en_value if isinstance(en_value, str) else ""
        missing = [code for code, _prop in LANGUAGES if not isinstance(entry.get(code), str)]
        if missing:
            gaps.append((k, missing))
    lines = [
        "// <auto-generated> - generated by tools/gen_strings.py",
        "// from tools/merged.json. Do not hand-edit; re-run the generator instead.",
        "// One dictionary per language (12 tables, canonical order id en es",
        "// pt fr de ru zh ja ko ar tr), one entry per unique literal",
        "// (inventory dedupe): 1 key = 1 string. A key missing a member",
        "// for some language emits the English value in that dict.",
        "using System.Collections.Generic;",
        "",
        "namespace Keystream.Core.Localization;",
        "",
        "/// <summary>Localized string tables (12 languages, canonical order:",
        "/// id, en, es, pt, fr, de, ru, zh, ja, ko, ar, tr.",
        "/// Invariant keys (brands, key names, chords, symbols) carry the same",
        "/// value in every table. Looked up through Localizer, never directly.",
        "/// </summary>",
        "public static class Strings",
        "{",
    ]
    for i, (_code, prop) in enumerate(LANGUAGES):
        lines.append(f"    public static readonly IReadOnlyDictionary<string, string> {prop} = new Dictionary<string, string>")
        lines.append("    {")
        for k in keys:
            lines.append(f'        ["{k}"] = "{cs(values[_code][k])}",')
        lines.append("    };")
        if i < len(LANGUAGES) - 1:
            lines.append("")
    lines += [
        "}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    filled = sum(len(missing) for _k, missing in gaps)
    for k, missing in gaps:
        print(f"warning: {k} missing: {', '.join(missing)}", file=sys.stderr)
    print(f"wrote {OUT} ({len(keys)} keys x 12 languages; {filled} entries filled from English)")


if __name__ == "__main__":
    main()
